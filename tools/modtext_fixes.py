#!/usr/bin/env python3
"""Corrections layered on top of the merged mod_text (applied by tools/merge_modtext.py).

merge_modtext.py rebuilds data/common and data/ffN/mod_text.json from the five old
mods. The old mods' game terms were not always the games' own words, so this module
holds the corrections and new keys that must survive a re-merge:

  FIXES      (file, key, lang, old, new, source)
             file is "common" or "ff1".."ff6". A fix to an override the merged
             file does not have yet starts that override as a copy of the
             merged common entry. lang "-" removes the override instead (after
             the fixes it equals the common entry).
  ADDITIONS  (file, key, entry, source): keys no old mod had, appended at the end.

Every FIXES row names the game table it comes from; read them with
tools/official_text.py (find / id). "old" must still match what the merge
produced, so a changed old mod is reported instead of overwritten.
The 2026-10-06 pass is described in docs/MODTEXT_MERGE.md ("Official-text fixes").
"""


def apply(common, overrides):
    """Apply ADDITIONS and FIXES in place. overrides: {game_number: dict}.
    Returns a list of problems (empty when every fix applied cleanly)."""
    problems = []
    merged_common = {k: dict(v) for k, v in common.items()}
    for f, key, lang, old, new, _src in FIXES:
        if f == "common":
            continue
        over = overrides[int(f[2:])]
        if lang == "-":
            if key not in over:
                problems.append(f"{f}: `{key}` has no override to remove")
            else:
                del over[key]
            continue
        if key not in over:
            if key not in merged_common:
                problems.append(f"{f}: `{key}` is not a common key")
                continue
            over[key] = dict(merged_common[key])
        if over[key].get(lang) != old:
            problems.append(f"{f}: `{key}` {lang} is {over[key].get(lang)!r}, expected {old!r}")
            continue
        over[key][lang] = new
    for f, key, lang, old, new, _src in FIXES:
        if f != "common":
            continue
        if key not in common or common[key].get(lang) != old:
            problems.append(f"common: `{key}` {lang} is {common.get(key, {}).get(lang)!r}, expected {old!r}")
            continue
        common[key][lang] = new
    for f, key, entry, _src in ADDITIONS:
        target = common if f == "common" else overrides[int(f[2:])]
        if key in target:
            problems.append(f"{f}: `{key}` already exists; remove it from ADDITIONS")
            continue
        target[key] = dict(entry)
    for g, over in overrides.items():
        for key, entry in over.items():
            if key in common and entry == common[key]:
                problems.append(f"ff{g}: `{key}` override equals the common entry")
    return problems


